/// Finds a `break` (or `continue`) leaving the statement being analyzed.
struct BreakFinder<'l> {
    /// Label of the analyzed statement, if any.
    label: Option<&'l str>,
    /// Nesting of loops / switches inside the analyzed statement.
    depth: u32,
    /// Also look for `continue` statements.
    continues: bool,
    found: bool,
}

impl<'a> Visit<'a> for BreakFinder<'_> {
    fn visit_break_statement(&mut self, it: &BreakStatement<'a>) {
        match &it.label {
            None => self.found |= self.depth == 0,
            Some(l) => self.found |= Some(l.name.as_str()) == self.label,
        }
    }

    fn visit_continue_statement(&mut self, it: &ContinueStatement<'a>) {
        if self.continues {
            match &it.label {
                None => self.found |= self.depth == 0,
                Some(l) => self.found |= Some(l.name.as_str()) == self.label,
            }
        }
    }

    fn visit_while_statement(&mut self, it: &WhileStatement<'a>) {
        self.depth += 1;
        walk::walk_while_statement(self, it);
        self.depth -= 1;
    }

    fn visit_do_while_statement(&mut self, it: &DoWhileStatement<'a>) {
        self.depth += 1;
        walk::walk_do_while_statement(self, it);
        self.depth -= 1;
    }

    fn visit_for_statement(&mut self, it: &ForStatement<'a>) {
        self.depth += 1;
        walk::walk_for_statement(self, it);
        self.depth -= 1;
    }

    fn visit_for_in_statement(&mut self, it: &ForInStatement<'a>) {
        self.depth += 1;
        walk::walk_for_in_statement(self, it);
        self.depth -= 1;
    }

    fn visit_for_of_statement(&mut self, it: &ForOfStatement<'a>) {
        self.depth += 1;
        walk::walk_for_of_statement(self, it);
        self.depth -= 1;
    }

    fn visit_switch_statement(&mut self, it: &SwitchStatement<'a>) {
        // `continue` inside a switch still targets the enclosing loop.
        if self.continues {
            let saved = self.continues;
            self.depth += 1;
            self.continues = false;
            walk::walk_switch_statement(self, it);
            self.continues = saved;
            self.depth -= 1;
            // Unlabeled `continue` in the switch targets us.
            let mut inner = BreakFinder {
                label: self.label,
                depth: 0,
                continues: true,
                found: false,
            };
            inner.only_continues(it);
            self.found |= inner.found;
        } else {
            self.depth += 1;
            walk::walk_switch_statement(self, it);
            self.depth -= 1;
        }
    }

    fn visit_function(&mut self, _: &Function<'a>, _: ScopeFlags) {}

    fn visit_arrow_function_expression(&mut self, _: &ArrowFunctionExpression<'a>) {}

    fn visit_class(&mut self, _: &Class<'a>) {}
}

impl BreakFinder<'_> {
    fn only_continues(&mut self, it: &SwitchStatement<'_>) {
        struct C(bool);
        impl<'a> Visit<'a> for C {
            fn visit_continue_statement(&mut self, it: &ContinueStatement<'a>) {
                self.0 |= it.label.is_none();
            }
            fn visit_while_statement(&mut self, _: &WhileStatement<'a>) {}
            fn visit_do_while_statement(&mut self, _: &DoWhileStatement<'a>) {}
            fn visit_for_statement(&mut self, _: &ForStatement<'a>) {}
            fn visit_for_in_statement(&mut self, _: &ForInStatement<'a>) {}
            fn visit_for_of_statement(&mut self, _: &ForOfStatement<'a>) {}
            fn visit_function(&mut self, _: &Function<'a>, _: ScopeFlags) {}
            fn visit_arrow_function_expression(&mut self, _: &ArrowFunctionExpression<'a>) {}
            fn visit_class(&mut self, _: &Class<'a>) {}
        }
        let mut c = C(false);
        walk::walk_switch_statement(&mut c, it);
        self.found |= c.0;
    }
}

fn breaks_out(body: &Statement<'_>, label: Option<&str>, continues: bool) -> bool {
    let mut f = BreakFinder {
        label,
        depth: 0,
        continues,
        found: false,
    };
    f.visit_statement(body);
    f.found
}

fn switch_breaks_out(cases: &[SwitchCase<'_>], label: Option<&str>) -> bool {
    let mut f = BreakFinder {
        label,
        depth: 0,
        continues: false,
        found: false,
    };
    for c in cases {
        for s in &c.consequent {
            f.visit_statement(s);
        }
    }
    f.found
}

/// Simple constant truthiness as used by code path analysis (`while (true)`, `while (1)`).
fn is_constant_truthy(e: &Expression<'_>) -> bool {
    match e.without_parentheses() {
        Expression::BooleanLiteral(b) => b.value,
        Expression::NumericLiteral(n) => n.value != 0.0 && !n.value.is_nan(),
        Expression::StringLiteral(s) => !s.value.is_empty(),
        Expression::ObjectExpression(_) | Expression::ArrayExpression(_) => true,
        _ => false,
    }
}

/// True when control may reach the end of `stmts` (fall through).
pub fn stmts_complete(stmts: &[Statement<'_>]) -> bool {
    stmts.iter().all(|s| completes(s, None))
}

/// True when control may flow past `stmt`. `label` is the label directly attached to it.
pub fn completes(stmt: &Statement<'_>, label: Option<&str>) -> bool {
    match stmt {
        Statement::ReturnStatement(_)
        | Statement::ThrowStatement(_)
        | Statement::BreakStatement(_)
        | Statement::ContinueStatement(_) => false,
        Statement::BlockStatement(b) => {
            stmts_complete(&b.body) || (label.is_some() && breaks_out(stmt, label, false))
        }
        Statement::IfStatement(i) => {
            completes(&i.consequent, None)
                || i.alternate.as_ref().is_none_or(|a| completes(a, None))
                || (label.is_some() && breaks_out(stmt, label, false))
        }
        Statement::LabeledStatement(l) => {
            completes(&l.body, Some(l.label.name.as_str()))
                || breaks_out(&l.body, Some(l.label.name.as_str()), false)
        }
        Statement::TryStatement(t) => {
            let main = stmts_complete(&t.block.body)
                || t.handler
                    .as_ref()
                    .is_some_and(|h| stmts_complete(&h.body.body));
            match &t.finalizer {
                Some(f) => main && stmts_complete(&f.body),
                None => main,
            }
        }
        Statement::WhileStatement(w) => {
            !is_constant_truthy(&w.test) || breaks_out(&w.body, label, false)
        }
        Statement::ForStatement(f) => {
            f.test.as_ref().is_some_and(|t| !is_constant_truthy(t))
                || breaks_out(&f.body, label, false)
        }
        Statement::DoWhileStatement(d) => {
            if is_constant_truthy(&d.test) {
                breaks_out(&d.body, label, false)
            } else {
                completes(&d.body, None) || breaks_out(&d.body, label, true)
            }
        }
        Statement::SwitchStatement(s) => {
            if !s.cases.iter().any(|c| c.test.is_none()) {
                return true;
            }
            s.cases.last().is_none_or(|c| stmts_complete(&c.consequent))
                || switch_breaks_out(&s.cases, label)
        }
        _ => true,
    }
}

/// True for TypedArray constructor names.
pub fn is_typed_array_name(name: &str) -> bool {
    matches!(
        name,
        "Int8Array"
            | "Uint8Array"
            | "Uint8ClampedArray"
            | "Int16Array"
            | "Uint16Array"
            | "Int32Array"
            | "Uint32Array"
            | "Float32Array"
            | "Float64Array"
            | "BigInt64Array"
            | "BigUint64Array"
    )
}

