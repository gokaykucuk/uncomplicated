const VUE_MODULES: [&str; 4] = [
    "vue",
    "@vue/composition-api",
    "@vue/runtime-core",
    "@vue/reactivity",
];

/// The `vue` export an identifier is bound to through an import (`import { ref as r } from 'vue'`).
pub fn vue_import_name<'a>(ctx: &Ctx<'a, '_>, id: &IdentifierReference<'_>) -> Option<&'a str> {
    let sym = ctx.symbol_of(id)?;
    let decl = ctx.symbol_decl(sym);
    let AstKind::ImportSpecifier(s) = decl.kind() else {
        return None;
    };
    let AstKind::ImportDeclaration(d) = ctx.parent_kind(decl.id()) else {
        return None;
    };
    if !VUE_MODULES.contains(&d.source.value.as_str()) {
        return None;
    }
    Some(match &s.imported {
        ModuleExportName::IdentifierName(n) => n.name.as_str(),
        ModuleExportName::IdentifierReference(n) => n.name.as_str(),
        ModuleExportName::StringLiteral(n) => n.value.as_str(),
    })
}

/// True if `id` is a default / namespace import of `vue`.
fn is_vue_namespace(ctx: &Ctx<'_, '_>, id: &IdentifierReference<'_>) -> bool {
    let Some(sym) = ctx.symbol_of(id) else {
        return false;
    };
    let decl = ctx.symbol_decl(sym);
    if !matches!(
        decl.kind(),
        AstKind::ImportDefaultSpecifier(_) | AstKind::ImportNamespaceSpecifier(_)
    ) {
        return false;
    }
    matches!(ctx.parent_kind(decl.id()), AstKind::ImportDeclaration(d) if VUE_MODULES.contains(&d.source.value.as_str()))
}

/// Name of the `vue` API a callee refers to: `ref` for `ref(...)` / `Vue.ref(...)`.
pub fn vue_callee_name<'a>(ctx: &Ctx<'a, '_>, callee: &Expression<'a>) -> Option<&'a str> {
    match callee.without_parentheses() {
        Expression::Identifier(id) => vue_import_name(ctx, id),
        Expression::StaticMemberExpression(m) => match &m.object {
            Expression::Identifier(o) if is_vue_namespace(ctx, o) => Some(m.property.name.as_str()),
            _ => None,
        },
        _ => None,
    }
}

fn last_object_arg<'b, 'a>(args: &'b [Argument<'a>]) -> Option<&'b ObjectExpression<'a>> {
    match args.last()?.as_expression().map(crate::helpers::strip_ts) {
        Some(Expression::ObjectExpression(o)) => Some(o),
        _ => None,
    }
}

/// The options object of a Vue component / instance defined in a script file:
/// `defineComponent({})`, `createApp({})`, `component('x', {})`, `Vue.component|mixin|extend(...)`,
/// `app.component|mixin(...)`, `new Vue({})`.
pub fn vue_component_object<'b, 'a>(kind: &'b AstKind<'a>) -> Option<&'b ObjectExpression<'a>> {
    match kind {
        AstKind::CallExpression(c) => {
            let ok = match crate::helpers::strip_ts(&c.callee) {
                Expression::Identifier(id) => matches!(
                    id.name.as_str(),
                    "defineComponent" | "createApp" | "component"
                ),
                Expression::StaticMemberExpression(m) => {
                    match crate::helpers::strip_ts(&m.object) {
                        Expression::Identifier(o) if o.name == "Vue" => {
                            matches!(m.property.name.as_str(), "component" | "mixin" | "extend")
                        }
                        Expression::Identifier(_) => {
                            matches!(m.property.name.as_str(), "component" | "mixin")
                        }
                        _ => false,
                    }
                }
                _ => false,
            };
            if ok {
                last_object_arg(&c.arguments)
            } else {
                None
            }
        }
        AstKind::NewExpression(n) => match &n.callee {
            Expression::Identifier(id) if id.name == "Vue" => last_object_arg(&n.arguments),
            _ => None,
        },
        _ => None,
    }
}

/// Static name of an object property key.
pub fn static_key<'a>(p: &ObjectProperty<'a>) -> Option<&'a str> {
    if p.computed {
        return match &p.key {
            PropertyKey::StringLiteral(s) => Some(s.value.as_str()),
            _ => None,
        };
    }
    crate::helpers::property_key_name(&p.key)
}

/// The value of property `name` in an object literal.
pub fn find_property<'b, 'a>(
    o: &'b ObjectExpression<'a>,
    name: &str,
) -> Option<&'b ObjectProperty<'a>> {
    o.properties.iter().find_map(|p| match p {
        ObjectPropertyKind::ObjectProperty(p) if static_key(p) == Some(name) => Some(&**p),
        _ => None,
    })
}

/// Body of a function-valued expression.
pub fn function_body<'b, 'a>(e: &'b Expression<'a>) -> Option<&'b FunctionBody<'a>> {
    match e.without_parentheses() {
        Expression::FunctionExpression(f) => f.body.as_deref(),
        Expression::ArrowFunctionExpression(a) => a.body.as_function_body(),
        _ => None,
    }
}

/// Visits the body of a function-valued expression (block or expression body). Returns false when
/// `e` is not a function.
pub fn visit_function_body<'a, V: Visit<'a>>(v: &mut V, e: &Expression<'a>) -> bool {
    match e.without_parentheses() {
        Expression::FunctionExpression(f) => {
            if let Some(b) = &f.body {
                for s in &b.statements {
                    v.visit_statement(s);
                }
            }
            true
        }
        Expression::ArrowFunctionExpression(a) => {
            match &a.body {
                ArrowFunctionBody::FunctionBody(b) => {
                    for s in &b.statements {
                        v.visit_statement(s);
                    }
                }
                body => {
                    if let Some(e) = body.as_expression() {
                        v.visit_expression(e);
                    }
                }
            }
            true
        }
        _ => false,
    }
}

