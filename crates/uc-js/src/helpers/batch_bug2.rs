/// Facts about the statements of one function body (nested functions excluded).
#[derive(Default, Debug, Clone, Copy)]
pub struct BodyFacts {
    /// A `return <expr>` statement.
    pub returns_value: bool,
    /// A bare `return;`.
    pub returns_empty: bool,
    pub throws: bool,
}

struct BodyScan(BodyFacts);

impl<'a> Visit<'a> for BodyScan {
    fn visit_return_statement(&mut self, it: &ReturnStatement<'a>) {
        if it.argument.is_some() {
            self.0.returns_value = true;
        } else {
            self.0.returns_empty = true;
        }
        walk::walk_return_statement(self, it);
    }

    fn visit_throw_statement(&mut self, it: &ThrowStatement<'a>) {
        self.0.throws = true;
        walk::walk_throw_statement(self, it);
    }

    fn visit_function(&mut self, _: &Function<'a>, _: ScopeFlags) {}

    fn visit_arrow_function_expression(&mut self, _: &ArrowFunctionExpression<'a>) {}

    fn visit_class(&mut self, _: &Class<'a>) {}
}

/// Scans the statements of a function body, without entering nested functions or classes.
pub fn body_facts(body: &FunctionBody<'_>) -> BodyFacts {
    let mut scan = BodyScan(BodyFacts::default());
    for s in &body.statements {
        scan.visit_statement(s);
    }
    scan.0
}

