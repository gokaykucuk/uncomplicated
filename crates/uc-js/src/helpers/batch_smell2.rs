/// Sonar's `getMainFunctionTokenLocation`: the name of a function declaration, the key of a
/// method / property whose value is the function, the `function` keyword otherwise, and the
/// last `=>` before the body for arrows.
pub fn sonar_function_loc(ctx: &Ctx<'_, '_>, node: &AstNode<'_>) -> Span {
    match node.kind() {
        AstKind::Function(f) => {
            if f.is_declaration()
                && let Some(id) = &f.id
            {
                return id.span;
            }
            if !f.is_declaration() {
                match ctx.parent_kind(node.id()) {
                    AstKind::MethodDefinition(m) => return m.key.span(),
                    AstKind::ObjectProperty(p) if p.value.span() == f.span => return p.key.span(),
                    _ => {}
                }
            }
            find_token(ctx, f.span, Kind::Function).unwrap_or(Span::new(f.span.start, f.span.start))
        }
        AstKind::ArrowFunctionExpression(a) => {
            let body_start = a.body.span().start;
            let toks = ctx.tokens_in(Span::new(a.span.start, body_start));
            toks.iter()
                .rev()
                .find(|t| t.kind() == Kind::Arrow)
                .map(|t| t.span())
                .unwrap_or(a.span)
        }
        k => k.span(),
    }
}

