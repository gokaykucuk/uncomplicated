/// `describe(...)`, `it.only(...)`, ...
pub fn is_test_framework_call(call: &CallExpression<'_>) -> bool {
    match &call.callee {
        Expression::Identifier(id) => TEST_FRAMEWORK_FUNCTIONS.contains(&id.name.as_str()),
        Expression::StaticMemberExpression(m) => {
            matches!(&m.object, Expression::Identifier(id) if TEST_FRAMEWORK_FUNCTIONS.contains(&id.name.as_str()))
        }
        Expression::ComputedMemberExpression(m) => {
            matches!(&m.object, Expression::Identifier(id) if TEST_FRAMEWORK_FUNCTIONS.contains(&id.name.as_str()))
        }
        _ => false,
    }
}

/// Parent of `id`, skipping parenthesized expressions only.
pub fn parent_skip_parens_only<'a, 's>(ctx: &Ctx<'a, 's>, id: NodeId) -> &'s AstNode<'a> {
    let mut cur = ctx.parent(id);
    while let AstKind::ParenthesizedExpression(_) = cur.kind() {
        if cur.id() == NodeId::ROOT {
            break;
        }
        cur = ctx.parent(cur.id());
    }
    cur
}

/// First token in `[from, to)` whose text equals `op`.
pub fn operator_token(ctx: &Ctx<'_, '_>, from: u32, to: u32, op: &str) -> Span {
    ctx.tokens_in(Span::new(from, to))
        .iter()
        .find(|t| ctx.text(t.span()) == op)
        .map(|t| t.span())
        .unwrap_or(Span::new(from, to))
}

/// Span of the first token at or after `pos`.
pub fn first_token(ctx: &Ctx<'_, '_>, pos: u32) -> Span {
    crate::helpers::ast::token_after(ctx, pos).unwrap_or(Span::new(pos, pos))
}

/// True if the call is a `foo.splice(...)`-like call; returns the identifier name of the
/// object root of a member callee (`a.b.c()` → `a`) when the callee is a member chain.
pub fn callee_root_identifier<'b, 'a>(
    call: &'b CallExpression<'a>,
) -> Option<&'b IdentifierReference<'a>> {
    let mut cur = strip_parens(&call.callee);
    let mut is_member = false;
    loop {
        match cur {
            Expression::StaticMemberExpression(m) => cur = strip_parens(&m.object),
            Expression::ComputedMemberExpression(m) => cur = strip_parens(&m.object),
            Expression::PrivateFieldExpression(m) => cur = strip_parens(&m.object),
            Expression::Identifier(id) if is_member => return Some(id),
            _ => return None,
        }
        is_member = true;
    }
}

/// Sonar's `isVendorFile`: vendor directories and well-known vendored library file names.
pub fn is_vendor_file(path: &str) -> bool {
    const DIRS: &[&str] = &[
        "contrib",
        "external",
        "externals",
        "third-party",
        "thirdparty",
        "vendor",
        "vendors",
    ];
    const LIBS: &[&str] = &[
        "backbone",
        "bluebird",
        "chartjs",
        "codemirror",
        "dompurify",
        "handlebars",
        "highlight",
        "jquery",
        "knockout",
        "lodash",
        "marked",
        "modernizr",
        "moment",
        "mootools",
        "punycode",
        "purify",
        "requirejs",
        "semver",
        "sprintf",
        "three",
        "underscore",
        "xregexp",
    ];
    const SUFFIXES: &[&str] = &[
        "amd", "all", "bundle", "core", "cjs", "custom", "debug", "esm", "full", "global", "min",
        "module", "nodes", "pack", "prod", "runtime", "slim", "tsl", "umd", "webgpu",
    ];
    let normalized = path.replace('\\', "/");
    let segments: Vec<&str> = normalized.split('/').collect();
    if segments
        .iter()
        .any(|s| DIRS.contains(&s.to_ascii_lowercase().as_str()))
    {
        return true;
    }
    let base = segments.last().copied().unwrap_or("");
    let lower = base.to_ascii_lowercase();
    for lib in LIBS {
        let Some(suffix) = lower.strip_prefix(lib) else {
            continue;
        };
        let Some(mid) = suffix.strip_suffix(".js") else {
            continue;
        };
        let ok = mid
            .split(['-', '.'])
            .filter(|t| !t.is_empty())
            .all(|t| SUFFIXES.contains(&t) || is_version_token(t));
        if ok {
            return true;
        }
    }
    false
}

fn is_version_token(t: &str) -> bool {
    let b = t.as_bytes();
    let rest = match b.first() {
        Some(b'v' | b'V' | b'r' | b'R') => &b[1..],
        _ => b,
    };
    rest.first().is_some_and(|c| c.is_ascii_digit())
        && rest.iter().all(|c| c.is_ascii_alphanumeric() || *c == b'_')
}

/// Tokens of a span without `{` / `}`; used for Sonar's "has required size" check.
pub fn spans_multiple_lines_without_braces(ctx: &Ctx<'_, '_>, first: Span, last: Span) -> bool {
    let not_brace = |t: &&oxc_parser::Token| !matches!(t.kind(), Kind::LCurly | Kind::RCurly);
    let start = ctx
        .tokens_in(first)
        .iter()
        .find(not_brace)
        .or_else(|| ctx.tokens_in(last).iter().find(not_brace));
    let end = ctx
        .tokens_in(last)
        .iter()
        .rev()
        .find(not_brace)
        .or_else(|| ctx.tokens_in(first).iter().rev().find(not_brace));
    match (start, end) {
        (Some(s), Some(e)) => ctx.line(e.end()) > ctx.line(s.start()),
        _ => false,
    }
}

/// Whether Sonar (which tries to parse every file as an ES module first and falls back to a
/// script) sees this file as a module. TypeScript is always parsed as a module. For JavaScript
/// without import/export syntax we re-parse as a module; callers should only do this when the
/// answer matters, since it costs a parse.
pub fn sonar_parses_as_module(ctx: &Ctx<'_, '_>) -> bool {
    if ctx.is_ts() || ctx.nodes().program().source_type.is_module() {
        return true;
    }
    let alloc = oxc_allocator::Allocator::default();
    let st = oxc_span::SourceType::mjs().with_jsx(true);
    let ret = oxc_parser::Parser::new(&alloc, ctx.src, st).parse();
    if ret.fatal_error || !ret.diagnostics.is_empty() {
        return false;
    }
    let program = alloc.alloc(ret.program);
    oxc_semantic::SemanticBuilder::new()
        .with_check_syntax_error(true)
        .build(program)
        .diagnostics
        .is_empty()
}

/// Ancestors of a node, nearest (the parent) first.
pub fn ancestors<'a, 's>(
    ctx: &Ctx<'a, 's>,
    id: NodeId,
) -> impl Iterator<Item = &'s AstNode<'a>> + 's {
    ctx.nodes().ancestors(id)
}

/// True if `text` contains one of `words` (ASCII case-insensitive) delimited by non-word
/// characters, like the regex `\b(w1|w2|...)\b/i`.
pub fn wordish_contains(text: &str, words: &[&str]) -> bool {
    let lower = text.to_ascii_lowercase();
    let b = lower.as_bytes();
    let is_word = |c: u8| c.is_ascii_alphanumeric() || c == b'_';
    words.iter().any(|w| {
        let mut from = 0;
        while let Some(i) = lower[from..].find(w) {
            let s = from + i;
            let e = s + w.len();
            if (s == 0 || !is_word(b[s - 1])) && (e >= b.len() || !is_word(b[e])) {
                return true;
            }
            from = s + 1;
        }
        false
    })
}

/// True if two statement lists are syntactically equivalent (pairwise same tokens).
pub fn same_statements(ctx: &Ctx<'_, '_>, a: &[Statement<'_>], b: &[Statement<'_>]) -> bool {
    a.len() == b.len()
        && a.iter()
            .zip(b)
            .all(|(x, y)| ctx.same_tokens(x.span(), y.span()))
}

