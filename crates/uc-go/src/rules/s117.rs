    #[test]
    fn names() {
        check(
            "S117",
            r#"package p

var global_var = 1

func f(okParam int, bad_param string) { // Noncompliant {{Rename this parameter to match the regular expression "^(_|[a-zA-Z0-9]+)$".}}
	local := 1
	bad_local := 2 // Noncompliant {{Rename this local variable to match the regular expression "^(_|[a-zA-Z0-9]+)$".}}
	var x_y int // Noncompliant
	const c_d = 1 // Noncompliant
	_ = 3
	for i_j := 0; i_j < 3; i_j++ { // Noncompliant
	}
	for k_v := range xs { // range variables are not checked
	}
	switch t_x := v.(type) { // Noncompliant
	}
	select {
	case m_n := <-ch: // Noncompliant
	}
	g := func(a_b int) {} // Noncompliant
}
"#,
        );
    }

