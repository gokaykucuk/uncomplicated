//! Local variable and function parameter names should comply with a naming convention.
use regex::Regex;

use crate::helpers_sonar::{full_match, is_generated, named_params};
use crate::prelude::*;

pub struct Rule {
    format: String,
    re: Option<Regex>,
}

impl Rule {
    pub fn new(p: &Params) -> Self {
        let format = p.str("format", "^(_|[a-zA-Z0-9]+)$").to_string();
        Self {
            re: full_match(&format),
            format,
        }
    }

    fn check(&self, re: &Regex, ctx: &Ctx<'_>, id: Nd<'_>, kind: &str) {
        if id.kind() == "identifier" && !re.is_match(ctx.text(id)) {
            ctx.report(
                id,
                format!(
                    "Rename this {kind} to match the regular expression \"{}\".",
                    self.format
                ),
            );
        }
    }

    fn check_list(&self, re: &Regex, ctx: &Ctx<'_>, list: Option<Nd<'_>>) {
        let Some(list) = list else { return };
        let mut c = list.walk();
        for id in list.named_children(&mut c) {
            self.check(re, ctx, id, "local variable");
        }
    }
}

fn has_define(n: Nd<'_>) -> bool {
    let mut c = n.walk();
    n.children(&mut c).any(|ch| ch.kind() == ":=")
}

impl GoRule for Rule {
    fn run_once(&self, ctx: &Ctx<'_>) {
        let Some(re) = &self.re else { return };
        if ctx.file.path.ends_with("_templ.go") || is_generated(ctx.src) {
            return;
        }
        for &n in &ctx.nodes {
            match n.kind() {
                "function_declaration" | "method_declaration" | "func_literal" => {
                    for p in named_params(n) {
                        self.check(re, ctx, p, "parameter");
                    }
                }
                "short_var_declaration" if ctx.enclosing_function(n).is_some() => {
                    self.check_list(re, ctx, n.child_by_field_name("left"));
                }
                "var_spec" | "const_spec" if ctx.enclosing_function(n).is_some() => {
                    let mut c = n.walk();
                    for id in n.children_by_field_name("name", &mut c) {
                        self.check(re, ctx, id, "local variable");
                    }
                }
                "type_switch_statement" => self.check_list(re, ctx, n.child_by_field_name("alias")),
                "receive_statement" if has_define(n) => {
                    self.check_list(re, ctx, n.child_by_field_name("left"))
                }
                _ => {}
            }
        }
    }
}

