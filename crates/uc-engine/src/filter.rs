//! Content-based file filters, mirroring SonarJS / sonar-go: bundles, minified files and generated
//! Go code are not analyzed.

use std::sync::LazyLock;

use regex::Regex;

/// `/*! license */ !function(` style prologue within the first 2 KB: a concatenated bundle.
static BUNDLE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?s)/\*.*\*/\s*[!;+(]function ?(?: [_$a-zA-Z][_$a-zA-Z0-9]*)?\(").unwrap());

static GO_GENERATED: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?m)^// Code generated .* DO NOT EDIT\.$").unwrap());

const MAX_AVG_LINE_LENGTH: usize = 200;

pub fn is_bundle(src: &str) -> bool {
    let end = src.floor_char_boundary(2048);
    BUNDLE.is_match(&src[..end])
}

pub fn is_minified(path: &str, src: &str) -> bool {
    if path.ends_with(".min.js") || path.ends_with("-min.js") {
        return true;
    }
    if !path.ends_with(".js") {
        return false;
    }
    let mut lines = memchr::memchr_iter(b'\n', src.as_bytes()).count() + 1;
    if src.ends_with('\n') {
        lines -= 1;
    }
    let total = src.len() - (src.as_bytes().iter().filter(|&&b| b == b'\n').count());
    lines > 0 && total / lines > MAX_AVG_LINE_LENGTH
}

/// Go files carrying the standard generated-code marker (before the package clause).
pub fn is_generated_go(src: &str) -> bool {
    let head = if src.starts_with("package ") {
        ""
    } else {
        match src.find("\npackage ") {
            Some(i) => &src[..i],
            None => &src[..src.floor_char_boundary(4096)],
        }
    };
    GO_GENERATED.is_match(head)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn filters() {
        assert!(is_bundle("/*! jQuery v3 | (c) */\n!function(e,t){}"));
        assert!(!is_bundle("/* hello */\nfunction a() {}"));
        assert!(is_minified("a.min.js", ""));
        assert!(is_minified("a.js", &"x".repeat(500)));
        assert!(!is_minified("a.ts", &"x".repeat(500)));
        assert!(is_generated_go("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n"));
        assert!(!is_generated_go("package x\n// Code generated by x. DO NOT EDIT.\n"));
    }
}
