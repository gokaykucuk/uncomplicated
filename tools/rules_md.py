#!/usr/bin/env python3
"""Generates docs/RULES.md from `unc rules --json`.

    python3 tools/rules_md.py --unc target/release/unc > docs/RULES.md
"""

import argparse
import collections
import json
import subprocess

REPOS = [
    ("js", "JavaScript / TypeScript", "SonarJS keys (`S*`) and extra rules (`UJ*`)."),
    ("go", "Go", "sonar-go keys (`S*`) and extra rules (`UG*`) modeled on go vet, staticcheck and gosec."),
    ("secrets", "Secrets", "Hard-coded credentials in any text file."),
    ("docker", "Dockerfile", ""),
    ("kubernetes", "Kubernetes", ""),
    ("actions", "GitHub Actions", ""),
    ("terraform", "Terraform", ""),
    ("css", "CSS, SCSS, Less", "SonarQube CSS keys."),
    ("deps", "Dependencies", "Known vulnerable or malicious package versions in lockfiles (needs `unc deps update`)."),
]

TYPES = {"BUG": "Bug", "VULNERABILITY": "Vulnerability", "CODE_SMELL": "Code smell", "SECURITY_HOTSPOT": "Hotspot"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--unc", default="target/release/unc")
    args = ap.parse_args()
    rules = json.loads(subprocess.check_output([args.unc, "rules", "--json"]))
    by_repo = collections.defaultdict(list)
    for r in rules:
        by_repo[r["lang"]].append(r)

    out = ["# Rules", "", "Generated by `tools/rules_md.py` from `unc rules --json`. **Default** means the rule is on",
           "in the default `sonar-way` profile; enable others with `[rules]` or `--profile all`.", ""]
    out += ["| Repository | Rules | On by default |", "|---|---|---|"]
    for key, name, _ in REPOS:
        rs = by_repo.get(key, [])
        if rs:
            out.append(f"| [{name}](#{anchor(name)}) | {len(rs)} | {sum(r['sonarWay'] for r in rs)} |")
    out.append("")
    for key, name, blurb in REPOS:
        rs = by_repo.get(key, [])
        if not rs:
            continue
        out += [f"## {name}", ""]
        if blurb:
            out += [blurb, ""]
        out += ["| Key | Type | Severity | Default | Title |", "|---|---|---|---|---|"]
        for r in sorted(rs, key=sort_key):
            title = r["title"].replace("|", "\\|")
            default = "✓" if r["sonarWay"] else ""
            out.append(f"| `{key}:{r['key']}` | {TYPES.get(r['type'], r['type'])} | {r['severity'].title()} | {default} | {title} |")
        out.append("")
    print("\n".join(out))


def anchor(title):
    return "".join(c for c in title.lower().replace(" ", "-") if c.isalnum() or c == "-")


def sort_key(r):
    k = r["key"]
    prefix = k.rstrip("0123456789")
    num = k[len(prefix):]
    return (prefix, int(num) if num else 0)


if __name__ == "__main__":
    main()
